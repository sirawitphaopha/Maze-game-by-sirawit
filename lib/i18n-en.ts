function en(s: string): string {
  const k = s.trim().replace(/\s+/g, " ");
  if (EN[k] !== undefined) return EN[k];
  for (const [rx, out] of EN_RX) {
    const m = k.match(rx);
    if (m) return typeof out === "function" ? out(m) : k.replace(rx, out);
  }
  return s;
}
